-- 013 — the fence gets a key that actually identifies a claim.
--
-- `012` and the two commits before this one gave `complete`, `fail` and `_defer` an
-- ownership fence: `WHERE id = %s AND owner_agent = %s AND lease_expires_at > now()`.
-- The intent was right — a worker whose lease lapsed mid-fetch must not be able to
-- finish a lead somebody else now owns — but `owner_agent` is not an identity. It is
-- the worker *name*, and `ingest.py`'s CLI default for it is the constant
-- `"ingest-cli"`. Two drains started from two terminals are both called `ingest-cli`,
-- so the fence cannot tell them apart: worker A's fence matches on worker B's fresh
-- lease and both proceed to write. That is the exact duplication the fence was added
-- to stop, surviving through the fence.
--
-- The same hole exists in time as well as in space. One worker that claims a lead,
-- loses the lease, and claims it again is two distinct pieces of in-flight work under
-- one name; a fence on the name alone cannot distinguish the stale run from the live
-- one either.
--
--
-- ## Why a token and not a better name
--
-- Giving each process a unique name (host + pid + a random suffix) closes the first
-- case and not the second, and it makes correctness depend on every caller remembering
-- to pass a good `--worker`. A default that is merely *usually* unique is the kind of
-- silent fallback this project does not ship.
--
-- A token generated by `claim` itself cannot be got wrong by a caller, because no
-- caller supplies it. `claim` stamps a fresh `gen_random_uuid()` on every row it takes
-- and returns it alongside the row; every fence carries it back. A second claim — by
-- anyone, under any name — overwrites the column, so the first claim's token stops
-- matching the instant its claim stops being current. `lease_token = <mine>` is
-- therefore a complete answer to "is this still my claim?", independent of the name
-- and independent of the clock.
--
--
-- ## Why nullable, and why no CHECK
--
-- Additive only: this is a shared, live cluster. Rows written before this migration
-- have `lease_token IS NULL`, and some of them still carry a stale `owner_agent` from
-- a drain that ended without tidying up. A NOT NULL column or a
-- `(owner_agent IS NULL) = (lease_token IS NULL)` CHECK would fail validation against
-- exactly those rows. They cost nothing as they are: a NULL token never equals
-- anything in SQL, so a fence carrying one fails closed, and `claim` stamps a real
-- token the moment such a row is next taken.
--
-- No index. Every fence that reads this column already narrows on `lead.id`, the
-- primary key; `claim` does not filter on it at all.

ALTER TABLE lead ADD COLUMN IF NOT EXISTS lease_token UUID;
